#!/usr/bin/env python3
"""Build the GitHub wiki from the lesson Markdown files.

The lessons in the repo root are the source of truth. The wiki is a generated
copy, so never edit it by hand:

- README.md becomes Home.md, and every other lesson keeps its file name
- links between lessons become wiki links ([[Text|Page Name]])
- links to other repo files (AGENTS.md, .github/..., .claude/...) become
  absolute GitHub URLs
- _Sidebar.md is built from the README's sections, and _Footer.md says where
  to edit

    python3 scripts/build_wiki.py <wiki-checkout-dir>   # writes pages there
"""

from __future__ import annotations

import os
import re
import sys
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = os.environ.get("GITHUB_REPOSITORY", "actuarialsociety/ds-training")
BRANCH = os.environ.get("WIKI_SOURCE_BRANCH", "main")
NOT_LESSONS = {"AGENTS.md", "CLAUDE.md"}
GENERATED_MARK = "<!-- generated by scripts/build_wiki.py; edit the repo, not the wiki -->"

# [text](target) not preceded by "!" (images keep their absolute URLs).
LINK_RE = re.compile(r"(?<!!)\[((?:[^\[\]]|\[[^\]]*\])*)\]\((<[^>]+>|[^)\s]+)\)")


def lessons() -> list[Path]:
    return sorted(p for p in ROOT.glob("*.md") if p.name not in NOT_LESSONS)


def page_name(md_file: str) -> str:
    return "Home" if md_file == "README.md" else md_file[:-3]


def rewrite_links(text: str, pages: set[str]) -> str:
    def repl(m: re.Match) -> str:
        label, target = m.group(1), m.group(2).strip("<>")
        if re.match(r"^[a-z]+:|^#", target):
            return m.group(0)
        path, _, anchor = urllib.parse.unquote(target).partition("#")
        path = path.removeprefix("./").rstrip("/")
        if path in pages:
            # Image links ([![..](..)](page)) can't use [[..]] syntax.
            if label.startswith("!["):
                slug = urllib.parse.quote(page_name(path).replace(" ", "-"))
                return f"[{label}]({slug}{'#' + anchor if anchor else ''})"
            return f"[[{label.replace('|', '/')}|{page_name(path)}]]"
        kind = "tree" if (ROOT / path).is_dir() else "blob"
        url = f"https://github.com/{REPO}/{kind}/{BRANCH}/{urllib.parse.quote(path)}"
        return f"[{label}]({url}{'#' + anchor if anchor else ''})"

    out, in_code = [], False
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("```"):
            in_code = not in_code
        out.append(line if in_code else LINK_RE.sub(repl, line))
    return "".join(out)


def sidebar(readme: str, pages: set[str]) -> str:
    lines = ["**[[ds-training|Home]]**"]
    for line in readme.splitlines():
        if line.startswith("## ") and "Maintaining" not in line:
            lines += ["", f"**{line[3:].strip()}**"]
        m = re.match(r"^- \[([^\]]+)\]\(\./([^)]+)\)", line)
        if m and urllib.parse.unquote(m.group(2)) in pages:
            lines.append(f"- [[{m.group(1)}|{page_name(urllib.parse.unquote(m.group(2)))}]]")
    return "\n".join(lines).strip() + "\n"


def main(out_dir: str) -> int:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    files = lessons()
    pages = {p.name for p in files}

    # Remove pages this script generated earlier whose lesson no longer exists.
    for old in out.glob("*.md"):
        if old.read_text(encoding="utf-8").startswith(GENERATED_MARK):
            old.unlink()

    for src in files:
        body = rewrite_links(src.read_text(encoding="utf-8"), pages)
        (out / f"{page_name(src.name)}.md").write_text(f"{GENERATED_MARK}\n{body}", encoding="utf-8")

    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    (out / "_Sidebar.md").write_text(f"{GENERATED_MARK}\n{sidebar(readme, pages)}", encoding="utf-8")
    (out / "_Footer.md").write_text(
        f"{GENERATED_MARK}\n_This wiki is generated from [{REPO}](https://github.com/{REPO}). "
        f"To change a page, edit the lesson in the repo and open a PR. Edits made here are overwritten._\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(files)} pages + sidebar/footer to {out}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    sys.exit(main(sys.argv[1]))
